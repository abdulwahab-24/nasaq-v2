import { defaultSrc, srcSet } from '../../utils/media';

/*
 * Responsive image. When the media carries a `mobile` variant (a different,
 * art-directed crop), small screens get that crop through <picture>.
 */
export default function ResponsiveImage({ media, sizes = '100vw', priority = false, className, style, ref, ...rest }) {
  const img = (
    <img
      ref={ref}
      className={className}
      src={defaultSrc(media)}
      srcSet={srcSet(media)}
      sizes={sizes}
      width={media.width}
      height={media.height}
      alt={media.alt}
      loading={priority ? 'eager' : 'lazy'}
      fetchPriority={priority ? 'high' : undefined}
      decoding="async"
      style={{ objectPosition: media.position, ...style }}
      {...rest}
    />
  );

  if (!media.mobile) return img;

  return (
    <picture>
      <source
        media="(max-width: 767.98px)"
        srcSet={srcSet(media.mobile)}
        sizes="100vw"
        width={media.mobile.width}
        height={media.mobile.height}
      />
      {img}
    </picture>
  );
}

// Tiny pre-blurred backdrop generated by scripts/build-media.mjs (if available).
export function Backdrop({ media, className = '' }) {
  if (!media?.blur) return null;
  return <img className={`backdrop ${className}`} src={`${media.src}-blur.webp`} alt="" aria-hidden="true" />;
}
